import { expect, test } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const api = `http://127.0.0.1:${process.env.E2E_API_PORT ?? 8010}`;

test("105 real samples paginate, and explicit task selection persists across pages", async ({ page }, testInfo) => {
  const stateCalls: string[] = [];
  page.on("request", request => { if (request.url().includes("/api/data-platform/state")) stateCalls.push(request.url()); });
  await page.goto("/projects/demo/datasets");
  await expect(page.getByRole("heading", { name: "数据集", exact: true })).toBeVisible();
  const me = await (await page.request.get(`${api}/api/me`)).json();
  const send = async (path: string, data: unknown) => {
    const response = await page.request.post(`${api}/api/data-platform${path}?project_id=demo`, { headers: { "X-CSRF-Token": me.csrf_token }, data });
    expect(response.status(), await response.text()).toBe(201); return response.json();
  };
  const name = `分页真实数据 ${Date.now()}`;
  const dataset = await send("/datasets", { name, modality: "文本", purpose: "训练", samples: Array.from({ length: 105 }, (_, index) => ({ name: `真实样本 ${index}`, input: `分页真实输入 ${name} ${index}`, split: "train" })) });
  const spec = await send("/specs", { name: `分页规范 ${name}`, type: "文本", labels: ["valid"], instructions: "保留明确样本成员" });
  const firstResponse = await page.request.get(`${api}/api/data-platform/datasets/${dataset.id}/samples?limit=50`);
  const first = await firstResponse.json();
  expect(first.total).toBe(105); expect(first.items).toHaveLength(50);
  await page.goto(`/projects/demo/datasets/${dataset.id}`);
  await expect(page.getByRole("heading", { name, exact: true })).toBeVisible();
  await expect(page.getByText(/105 个样本/, { exact: false }).first()).toBeVisible();
  await expect(page.locator(".platform-table tbody tr")).toHaveCount(50);
  await page.getByRole("button", { name: "下一页", exact: true }).click();
  await expect(page).toHaveURL(/cursor=/);
  await expect(page.locator(".platform-table tbody tr")).toHaveCount(50);
  await expect(page.getByRole("button", { name: first.items[0].name, exact: true })).toHaveCount(0);
  await page.goto("/projects/demo/annotation/tasks");
  await page.locator(".platform-page-heading").getByRole("button", { name: "新建任务", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("任务名称", { exact: true }).fill(`分页任务 ${name}`);
  await dialog.getByLabel("输入数据集", { exact: true }).selectOption(dataset.id);
  await dialog.getByLabel("标注规范", { exact: true }).selectOption(spec.id);
  await expect(dialog.getByRole("checkbox")).toHaveCount(50);
  await expect(dialog.getByText(/已选择 0 个样本/)).toBeVisible();
  await dialog.getByRole("button", { name: "选择本页全部样本" }).click();
  await expect(dialog.getByText(/已选择 50 个样本/)).toBeVisible();
  const nextPage = page.waitForResponse(response => response.url().includes(`/datasets/${dataset.id}/samples`) && response.url().includes("cursor=") && response.ok());
  await dialog.getByRole("button", { name: "后一页样本" }).click();
  const second = await (await nextPage).json();
  await expect(dialog.getByRole("checkbox").first()).not.toBeChecked();
  await dialog.getByRole("checkbox").first().check();
  await expect(dialog.getByText(/已选择 51 个样本/)).toBeVisible();
  await dialog.getByRole("button", { name: "前一页样本" }).click();
  await expect(dialog.getByRole("checkbox").first()).toBeChecked();
  await expect(dialog.getByText(/已选择 51 个样本/)).toBeVisible();
  const submission = page.waitForRequest(request => request.method() === "POST" && new URL(request.url()).pathname === "/api/data-platform/tasks");
  await dialog.getByRole("button", { name: "创建", exact: true }).click();
  const submitted = (await submission).postDataJSON();
  expect(new Set(submitted.sampleIds)).toEqual(new Set([...first.items.map((row: { id: string }) => row.id), second.items[0].id]));
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("heading", { name: `分页任务 ${name}`, exact: true })).toBeVisible();
  const taskId = new URL(page.url()).pathname.split("/").at(-1);
  const members = await (await page.request.get(`${api}/api/data-platform/tasks/${taskId}/samples?limit=200`)).json();
  expect(members.total).toBe(51); expect(members.items).toHaveLength(51);
  expect(stateCalls).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("task-paged-selection.png"), fullPage: true });
});

