#!/usr/bin/env node
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawn, spawnSync } = require('node:child_process');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');

const root = path.resolve(__dirname, '..');
const python = path.join(root, '.local-photos/venv/bin/python');
const artifacts = path.join(root, '.local-photos/browser-tests');
fs.mkdirSync(artifacts, { recursive: true });
const fixtureRoot = fs.mkdtempSync(path.join(artifacts, 'run-'));
const fixtureFolder = path.join(fixtureRoot, 'Trip');
const created = spawnSync(python, ['-c', 'import sys; from pathlib import Path; sys.path.insert(0,"local/photos/tests"); from test_photos import fixture; fixture(Path(sys.argv[1]))', fixtureFolder], { cwd: root, encoding: 'utf8' });
assert.equal(created.status, 0, created.stderr);
const server = spawn(python, ['local/photos/app.py', '--port', '0', '--offline-map', '--folder', fixtureFolder, '--state', path.join(fixtureRoot, 'state')], { cwd: root, stdio: ['ignore', 'pipe', 'pipe'] });
let browser, baseURL;
async function ready() {
  return new Promise((resolve, reject) => {
    let output = '';
    const timeout = setTimeout(() => reject(new Error('Local test server did not start')), 20000);
    server.stdout.on('data', chunk => { output += chunk; const match = output.match(/(?:Local Photos|本地相册): (http:\/\/127\.0\.0\.1:\d+)/); if (match) { clearTimeout(timeout); resolve(match[1]); } });
    server.once('error', error => { clearTimeout(timeout); reject(error); });
    server.once('exit', code => { clearTimeout(timeout); reject(new Error(`Test server exited: ${code}`)); });
  });
}
async function main() {
  baseURL = await ready();
  browser = await chromium.launch({ channel: 'chromium', headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [], remote = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.route('**/*', route => {
    const url = new URL(route.request().url());
    if (['http:', 'https:'].includes(url.protocol) && url.origin !== baseURL) { remote.push(url.origin); return route.abort(); }
    return route.continue();
  });
  await page.goto(`${baseURL}/local-photos/`, { waitUntil: 'networkidle' });
  await page.waitForFunction(() => document.querySelectorAll('.photo-card').length === 7);
  assert.equal(await page.locator('.photo-card img').count(), 7);
  await page.screenshot({ path: path.join(fixtureRoot, 'gallery-desktop.png'), fullPage: true });
  await page.locator('#search').fill('moment-0');
  await page.waitForFunction(() => document.querySelectorAll('.photo-card').length === 1);
  await page.getByRole('button', { name: '查看 moment-0.jpg', exact: true }).click();
  await page.locator('#favorite-photo').click();
  await page.locator('#custom-album').fill('Family trip');
  await page.locator('#tags').fill('holiday, family');
  await page.locator('#note').fill('This note stays local unless explicitly included in a story.');
  await page.locator('#annotation-form button[type=submit]').click();
  await page.waitForFunction(() => document.querySelector('#save-status').textContent.includes('已保存'));
  await page.locator('#close-photo').click();
  await page.locator('#search').fill('');
  await page.waitForFunction(() => document.querySelectorAll('.photo-card').length === 7);
  await page.locator('[data-view=favorites]').click();
  await page.waitForFunction(() => document.querySelectorAll('.photo-card').length === 1);
  await page.locator('[data-view=all]').click();
  await page.waitForFunction(() => document.querySelectorAll('.photo-card').length === 7);
  await page.locator('#check-duplicates').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('完全重复照片'));
  await page.locator('[data-view=duplicates]').click();
  await page.waitForFunction(() => document.querySelectorAll('.photo-card').length === 2);
  await page.locator('[data-view=journeys]').click();
  await page.waitForFunction(() => document.querySelectorAll('.timeline-moment').length === 7 && document.querySelectorAll('#route-map .map-pin').length > 0);
  await page.locator('#journey-scrubber').fill('3');
  assert.match(await page.locator('#replay-position').textContent(), /4 \/ 7/);
  await page.locator('#replay').click();
  await page.waitForFunction(() => Number(document.querySelector('#journey-scrubber').value) > 3);
  await page.locator('#replay').click();
  await page.locator('#map-in').click();
  await page.locator('#map-fit').click();
  await page.locator('#new-journey').click();
  await page.locator('#journey-name').fill('Our spring adventure');
  await page.locator('#journey-start').fill('2024-05-10');
  await page.locator('#journey-end').fill('2024-05-15');
  await page.locator('#journey-intro').fill('A week of small discoveries.');
  await page.locator('#journey-form button[type=submit]').click();
  await page.waitForFunction(() => document.querySelector('#journey-title').textContent === 'Our spring adventure');
  await page.screenshot({ path: path.join(fixtureRoot, 'time-map-desktop.png'), fullPage: true });
  await page.locator('.timeline-open').first().click();
  await page.waitForFunction(() => document.querySelector('#photo-dialog').open);
  await page.locator('#close-photo').click();
  await page.locator('#share-story').click();
  assert.equal(await page.locator('#story-locations').isChecked(), false);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#story-form button[type=submit]').click();
  const download = await downloadPromise;
  const storyPath = path.join(fixtureRoot, 'story.html');
  await download.saveAs(storyPath);
  const story = fs.readFileSync(storyPath, 'utf8');
  assert(!story.includes('moment-0.jpg'));
  assert(!story.includes('This note stays local'));
  assert(story.includes('位置和图片元数据已移除'));
  assert.equal((story.match(/data:image\/jpeg;base64/g) || []).length, 7);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(100);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile view overflows');
  await page.screenshot({ path: path.join(fixtureRoot, 'time-map-mobile.png'), fullPage: true });
  await page.locator('[data-view=all]').click();
  await page.waitForFunction(() => document.querySelectorAll('.photo-card').length === 7 && !document.querySelector('#gallery').hidden);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile gallery overflows');
  const storyPage = await context.newPage();
  await storyPage.goto(pathToFileURL(storyPath).href, { waitUntil: 'load' });
  assert.equal(await storyPage.locator('figure').count(), 7);
  await storyPage.screenshot({ path: path.join(fixtureRoot, 'story-mobile.png'), fullPage: true });
  assert.deepEqual(remote, [], 'Photo app requested external resources');
  assert.deepEqual(errors, [], 'Photo app emitted runtime errors');
  await context.close();
  console.log(`Headless checks passed: browsing, search, favorites, annotations, duplicates, GPS timeline, playback, albums, offline story, mobile layout and no external requests. Artifacts: ${fixtureRoot}`);
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); server.kill('SIGTERM'); });
