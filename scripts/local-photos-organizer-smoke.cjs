const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {spawn} = require('node:child_process');
const {chromium} = require('playwright');
const root = path.resolve(__dirname,'..');
const artifacts = path.join(root,'.local-photos/browser-tests'); fs.mkdirSync(artifacts,{recursive:true});
const fixtureRoot = fs.mkdtempSync(path.join(artifacts,'organizer-'));
const server = spawn(path.join(root,'.local-photos/venv/bin/python'),['local/photos/tests/organizer_server.py',fixtureRoot],{cwd:root,stdio:['ignore','pipe','pipe']});
let browser;
function ready(){return new Promise((resolve,reject)=>{let output='';const timer=setTimeout(()=>reject(new Error('Fixture server timeout')),20000);server.stdout.on('data',data=>{output+=data;const match=output.match(/Test Organizer: (http:\/\/127\.0\.0\.1:\d+)/);if(match){clearTimeout(timer);resolve(match[1]);}});server.once('error',reject);});}
async function main(){
 const base=await ready(); browser=await chromium.launch({channel:'chromium',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage();
 const errors=[],remote=[];page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/*',route=>{const url=new URL(route.request().url());if(['http:','https:'].includes(url.protocol)&&url.origin!==base){remote.push(url.origin);return route.abort();}return route.continue();});
 await page.goto(base+'/local-photos/#cleanup',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===2);
 assert.equal(await page.locator('#library-tools').isVisible(),false);
 assert.equal(await page.locator('.primary-nav button').count(),3);
 assert((await page.locator('.cleanup-description').first().textContent()).includes('蓝色背包'));
 await page.locator('.cleanup-action.keep').first().click();
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===1);
 await page.locator('[data-cleanup-tab=retained]').click();
 await page.waitForFunction(()=>document.querySelector('.cleanup-action.keep')?.getAttribute('aria-pressed')==='true');
 await page.locator('.cleanup-undo-action').first().click();
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===0);
 await page.locator('[data-cleanup-tab=pending]').click();
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===2);
 await page.locator('.cleanup-card-preview').first().click();
 await page.waitForFunction(()=>document.querySelector('#photo-dialog').open);
 assert.equal(await page.locator('#photo-dialog .photo-details').isVisible(),false);
 const initialWidth=await page.locator('#photo-frame img').evaluate(image=>image.getBoundingClientRect().width);
 await page.locator('#photo-zoom-in').click();
 assert.equal(await page.locator('#photo-zoom-value').textContent(),'1.5×');
 assert(await page.locator('#photo-frame img').evaluate((image,width)=>image.getBoundingClientRect().width>width*1.2,initialWidth));
 await page.locator('#photo-zoom-fit').click();
 await page.locator('#close-photo').click();
 assert(await page.locator('.cleanup-description').first().evaluate(element=>element.scrollHeight<=element.clientHeight));
 await page.screenshot({path:path.join(fixtureRoot,'cleanup-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:path.join(fixtureRoot,'cleanup-mobile.png'),fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.locator('#cleanup-select-loaded').check();
 assert.equal(await page.locator('.cleanup-select input:checked').count(),2);
 await page.locator('#cleanup-delete-selected').click();
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===0);
 assert.equal(await page.locator('dialog[open]').count(),0,'Deletion must not show an app confirmation');
 assert.equal(fs.readdirSync(path.join(fixtureRoot,'Photos')).filter(name=>name.endsWith('.jpg')).length,5);
 assert.equal(fs.readdirSync(path.join(fixtureRoot,'Trash')).length,2);
 assert.deepEqual(JSON.parse(fs.readFileSync(path.join(fixtureRoot,'native-calls.json'),'utf8')),{calls:1,items:2});
 await page.goto(base+'/local-photos/#organize',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>document.querySelectorAll('.photo-card').length===5);
 await page.locator('.filter-menu summary').click();
 await page.locator('#content-type').selectOption('screenshot');
 await page.locator('#content-category').selectOption('product');
 await page.locator('.filter-menu summary').click();
 await page.locator('#search').fill('测试品牌');
 await page.locator('#search-mode').selectOption('semantic');
 await page.waitForFunction(()=>document.querySelectorAll('.photo-card').length===5);
 assert.equal(fs.readdirSync(path.join(fixtureRoot,'Photos')).filter(name=>name.endsWith('.jpg')).length,5);
 await page.locator('.photo-open').first().click();
 await page.waitForFunction(()=>document.querySelector('#photo-category').options.length>1);
 await page.locator('#annotation-form .photo-extra summary').click();
 await page.locator('#photo-category').selectOption('invoice');await page.locator('#photo-review').selectOption('keep');
 await page.locator('#annotation-form button[type=submit]').click();
 await page.waitForFunction(()=>document.querySelector('#save-status').textContent.includes('已保存'));
 assert((await page.locator('#ocr-text').textContent()).includes('测试品牌'));
 await page.locator('#close-photo').click();
 assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
 await context.close();console.log('Organizer checks passed: thumbnail grid, one-sentence descriptions, immediate actions, undo, enlarged preview, filters, native deletion adapter and mobile layout. Artifacts: '+fixtureRoot);
}
main().catch(error=>{console.error(error.stack);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();server.kill('SIGTERM');});
