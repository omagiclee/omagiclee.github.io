const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '..');
const artifacts = path.join(root, '.local-photos/browser-tests'); fs.mkdirSync(artifacts,{recursive:true});
const fixtureRoot = fs.mkdtempSync(path.join(artifacts,'organizer-'));
const server = spawn(path.join(root,'.local-photos/venv/bin/python'),['local/photos/tests/organizer_server.py',fixtureRoot],{cwd:root,stdio:['ignore','pipe','pipe']});
let browser;
function ready(){return new Promise((resolve,reject)=>{let output='';const timer=setTimeout(()=>reject(new Error('Fixture server timeout')),20000);server.stdout.on('data',data=>{output+=data;const m=output.match(/Test Organizer: (http:\/\/127\.0\.0\.1:\d+)/);if(m){clearTimeout(timer);resolve(m[1]);}});server.once('error',reject);});}
async function main(){
 const base=await ready();browser=await chromium.launch({channel:'chromium',headless:true});
 const context=await browser.newContext({viewport:{width:1500,height:1050}}),page=await context.newPage();
 const errors=[],remote=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',route=>{const u=new URL(route.request().url());if(['http:','https:'].includes(u.protocol)&&u.origin!==base){remote.push(u.origin);return route.abort();}route.continue();});
 await page.goto(base+'/local-photos/#organize',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>document.querySelector('#organized-count').textContent==='7');
 assert.equal(await page.locator('.organize-select').count(),7);
 await page.locator('#content-type').selectOption('screenshot');
 await page.locator('.category-chip').filter({hasText:'商品／电商'}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.photo-card').length===7);
 await page.locator('#search').fill('测试品牌');
 await page.waitForFunction(()=>document.querySelectorAll('.photo-card').length===7);
 await page.locator('#search-mode').selectOption('semantic');
 await page.waitForTimeout(1000);
 assert.equal(await page.locator('.photo-card').count(),7);
 await page.locator('#select-page').click();await page.locator('#review-delete').click();
 await page.waitForFunction(()=>document.querySelector('#delete-count').textContent==='7');
 assert.equal(fs.readdirSync(path.join(fixtureRoot,'Photos')).filter(x=>x.endsWith('.jpg')).length,7);
 await page.locator('#content-review').selectOption('delete');
 await page.locator('.photo-open').first().click();
 await page.waitForFunction(()=>document.querySelector('#photo-category').options.length>1);
 await page.locator('#photo-category').selectOption('invoice');await page.locator('#photo-review').selectOption('keep');
 await page.locator('#annotation-form button[type=submit]').click();
 await page.waitForFunction(()=>document.querySelector('#save-status').textContent.includes('已保存'));
 assert((await page.locator('#ocr-text').textContent()).includes('测试品牌'));
 await page.locator('#close-photo').click();
 await page.locator('#content-review').selectOption('keep');
 await page.locator('.category-chip').filter({hasText:'发票／票据'}).click();
 await page.locator('#search-mode').selectOption('keyword');
 await page.waitForFunction(()=>document.querySelectorAll('.photo-card').length===1);
 await page.screenshot({path:path.join(fixtureRoot,'organizer-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:path.join(fixtureRoot,'organizer-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
 await context.close();console.log('Organizer checks passed: categories, OCR/semantic filters, human correction, review-only cleanup, mobile and no external requests. Artifacts: '+fixtureRoot);
}
main().catch(e=>{console.error(e.stack);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();server.kill('SIGTERM');});
