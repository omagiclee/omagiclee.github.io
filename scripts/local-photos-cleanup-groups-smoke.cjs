const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {spawn}=require('node:child_process');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
const artifacts=path.join(root,'.local-photos/browser-tests');fs.mkdirSync(artifacts,{recursive:true});
const fixture=fs.mkdtempSync(path.join(artifacts,'cleanup-groups-'));
const server=spawn(path.join(root,'.local-photos/venv/bin/python'),['local/photos/tests/organizer_server.py',fixture,'--grouped'],{cwd:root,stdio:['ignore','pipe','pipe']});
let browser;
function ready(){return new Promise((resolve,reject)=>{let out='';const timeout=setTimeout(()=>reject(Error('Fixture did not start')),20000);server.stdout.on('data',data=>{out+=data;const m=out.match(/Test Organizer: (http:\/\/127\.0\.0\.1:\d+)/);if(m){clearTimeout(timeout);resolve(m[1]);}});server.stderr.on('data',data=>process.stderr.write(data));server.once('error',reject);});}
async function main(){
 const base=await ready();browser=await chromium.launch({channel:'chromium',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1050}}),page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',route=>{const u=new URL(route.request().url());return ['http:','https:'].includes(u.protocol)&&u.origin!==base?route.abort():route.continue();});
 await page.goto(base+'/local-photos/#cleanup',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===5);
 assert.equal(await page.locator('.cleanup-group').count(),4);
 assert.equal(await page.locator('#cleanup-count-pending').textContent(),'5');
 assert.equal(await page.locator('#cleanup-group-A .cleanup-description').first().textContent(),'背包商品页面');
 await page.locator('#cleanup-group-A details summary').first().click();
 assert(await page.locator('#cleanup-group-A details p').first().isVisible());
 await page.locator('#cleanup-group-A .cleanup-card-preview').first().click();
 assert(await page.locator('#photo-dialog').isVisible());assert((await page.locator('#cleanup-preview-caption').textContent()).includes('背包商品页面'));
 await page.locator('#photo-zoom-in').click();assert.equal(await page.locator('#photo-zoom-value').textContent(),'1.5×');await page.locator('#close-photo').click();
 await page.locator('#cleanup-group-A .cleanup-group-toggle').click();assert(await page.locator('#cleanup-rows-A').isHidden());assert.equal(await page.locator('.cleanup-select input:checked').count(),0);
 await page.locator('#cleanup-groups button').first().click();assert(await page.locator('#cleanup-rows-A').isVisible());
 await page.locator('[data-select-group=C]').check();assert.equal(await page.locator('#cleanup-group-C .cleanup-select input:checked').count(),1,'Group selection must exclude manually retained items');
 await page.locator('#cleanup-clear-selection').click();
 await page.locator('[data-select-group=A]').check();assert.equal(await page.locator('.cleanup-select input:checked').count(),2);
 await page.locator('#cleanup-group-A .cleanup-action.keep').first().click();
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-select input:checked').length===1);
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===4);
 assert.equal(await page.locator('#cleanup-count-pending').textContent(),'4');
 await page.evaluate(()=>load());
 assert.equal(await page.locator('.cleanup-card').count(),4,'Kept items must stay out of pending after refresh');
 await page.locator('[data-cleanup-tab=retained]').click();
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===2);
 assert.equal(await page.locator('#cleanup-count-retained').textContent(),'2');
 await page.locator('#cleanup-group-A .cleanup-undo-action').first().click();
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===1);
 await page.locator('[data-cleanup-tab=pending]').click();
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===5);
 assert.equal(await page.locator('.cleanup-select input:checked').count(),0);
 await page.locator('#cleanup-group-A .cleanup-select input').first().check();
 const selectedID=await page.locator('#cleanup-group-A .cleanup-card').first().getAttribute('data-id');
 const routePattern='**/api/photos?*';
 await page.route(routePattern,async route=>{const response=await route.fetch(),d=await response.json();for(const p of d.photos)if(p.id===selectedID)p.deletion_version='changed-version';await route.fulfill({response,json:d});});
 await page.evaluate(()=>load());assert.equal(await page.locator('.cleanup-select input:checked').count(),0,'A changed photo version must clear the frozen selection');
 await page.unroute(routePattern);await page.evaluate(()=>load());
 await page.locator('[data-select-group=A]').check();await page.locator('[data-cleanup-tab=candidate]').click();
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===2);assert.equal(await page.locator('.cleanup-select input:checked').count(),0);
 await page.locator('[data-cleanup-tab=pending]').click();await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===5);
 await page.screenshot({path:path.join(fixture,'desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.locator('#cleanup-preview-size').selectOption('large');assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));await page.screenshot({path:path.join(fixture,'mobile.png'),fullPage:true});
 await page.setViewportSize({width:1440,height:1050});
 const expected=await page.locator('#cleanup-group-A .cleanup-card').evaluateAll(cards=>cards.map(c=>c.dataset.id));
 let payload;page.on('request',request=>{if(request.url().endsWith('/api/delete-batch'))payload=request.postDataJSON();});
 await page.locator('[data-select-group=A]').check();await page.locator('#cleanup-delete-selected').click();
 await page.waitForFunction(()=>document.querySelectorAll('.cleanup-card').length===3);
 assert.deepEqual(payload.items.map(x=>x.id).sort(),expected.sort());assert(payload.items.every(x=>typeof x.version==='string'&&x.version));
 assert.equal(await page.locator('#cleanup-group-A').count(),0);assert.equal(await page.locator('#cleanup-group-H .cleanup-card').count(),1);
 assert.deepEqual(JSON.parse(fs.readFileSync(path.join(fixture,'native-calls.json'))),{calls:1,items:2});
 assert.equal(fs.readdirSync(path.join(fixture,'Photos')).filter(n=>n.endsWith('.jpg')).length,5);
 assert.deepEqual(errors,[]);console.log('Grouped cleanup passed: descriptions, zoom, collapse, retained items, frozen versions, tab scope, mobile, exact batch IDs. '+fixture);
 await context.close();
}
main().catch(e=>{console.error(e.stack);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();server.kill('SIGTERM');});
